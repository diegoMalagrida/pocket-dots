#!/usr/bin/env python3
# Generates the [pywal] scheme of a spicetify theme from the pywal palette.
#
# Many wallpapers give grey pywal palettes (saturation ~0-20%), so an accent
# taken "as is" barely shows. Here we take the wallpaper's dominant HUE and
# push its saturation/lightness up -> a vivid accent that changes colour with
# every wallpaper, yet keeps the real hue of the image.
#
# The color.ini of 'termspot' ships 19 schemes of its own (Fdeox, Synthwave...),
# so the file is NOT overwritten: only the [pywal] block is inserted/replaced
# and the rest stays untouched (so a 'git pull' of the theme loses nothing of
# ours, nor the other way round, and you can try the stock schemes with
# `spicetify config color_scheme Fdeox`).
#
# Usage: spicetify-colors.py [path/to/color.ini]
#        (default ~/.config/spicetify/Themes/termspot/color.ini)
import json, sys, os, re, colorsys

HOME = os.path.expanduser("~")
SRC  = os.path.join(HOME, ".cache/wal/colors.json")
OUT  = sys.argv[1] if len(sys.argv) > 1 else \
       os.path.join(HOME, ".config/spicetify/Themes/termspot/color.ini")

try:
    d = json.load(open(SRC))
except Exception as e:
    sys.stderr.write("no colors.json: %s\n" % e)
    sys.exit(1)

sp, c = d["special"], d["colors"]

def h2rgb(h): h = h.lstrip("#"); return tuple(int(h[i:i+2], 16) / 255 for i in (0, 2, 4))
def H(r, g, b): return "%02X%02X%02X" % (round(r*255), round(g*255), round(b*255))
def strip(x): return x.lstrip("#").upper()

cols = [c["color%d" % i] for i in range(16)]
sat  = lambda h: colorsys.rgb_to_hls(*h2rgb(h))[2]
# dominant hue = the most saturated of the chromatic colours (skips blacks/greys 0,7,8,15)
best = max(cols[1:7] + cols[9:15], key=sat)
hue  = colorsys.rgb_to_hls(*h2rgb(best))[0]

mk   = lambda l, s: H(*colorsys.hls_to_rgb(hue, l, s))
bl   = colorsys.rgb_to_hls(*h2rgb(sp["background"]))[1]
# Surfaces: dark but WITH hue, which is what gives the phosphor look. The ramp
# (0.06 / 0.12 / 0.26 above the background) and the 0.24 saturation reproduce
# the separation of termspot's Fdeox scheme, measured on its own values.
tint = lambda l: mk(min(l, 0.30), 0.24)

accent  = mk(0.62, 0.72)   # play / active / bar / selected
accent2 = mk(0.72, 0.72)   # hover

body = f"""text               = {strip(sp['foreground'])}
subtext            = {strip(c['color8'])}
main               = {strip(sp['background'])}
accent             = {accent}
accent-active      = {accent2}
accent-inactive    = {strip(sp['background'])}
banner             = {accent}
border-active      = {accent}
border-inactive    = {tint(bl + 0.12)}
header             = {tint(bl + 0.26)}
highlight          = {tint(bl + 0.06)}
notification       = {accent}
notification-error = FF5C57
"""

section = "[pywal]\n; Generated by spicetify-colors.py from ~/.cache/wal/colors.json — do not edit by hand\n" + body

os.makedirs(os.path.dirname(OUT), exist_ok=True)
old = open(OUT).read() if os.path.exists(OUT) else ""

# Replaces the existing [pywal] block (up to the next [section] or EOF).
# If there is none, it appends one at the end, leaving the theme's schemes intact.
pat = re.compile(r"^\[pywal\][^\[]*", re.MULTILINE)
new = pat.sub(section, old, count=1) if pat.search(old) else \
      (old.rstrip("\n") + "\n\n" + section if old.strip() else section)

open(OUT, "w").write(new)
