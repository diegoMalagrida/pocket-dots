#!/usr/bin/env bash
# Thunar's language is set by the rice's language layer, not by the system's.
#
# The system is in en_US and the shell (Config.language, in
# ~/.config/quickshell-rice.json) is in Spanish, so by default you got Thunar
# in English with the right-click menu in Spanish: half and half, which is the
# one thing that will not do. This reads the rice's language and brings the two
# halves into line -- Thunar's interface through LANGUAGE (set by the wrapper
# ~/.local/bin/thunar) and the right-click menu actions by rewriting uca.xml,
# which has no way of translating itself.
#
#   thunar-language.sh          -> uses the rice's language
#   thunar-language.sh en       -> forces one
#
# Prints the code it applied (es|en), which is what the wrapper consumes.
set -uo pipefail

RICE="$HOME/.config/quickshell-rice.json"
DESTINO="$HOME/.config/Thunar/uca.xml"

LOC="${1:-}"
if [ -z "$LOC" ] && [ -r "$RICE" ]; then
	LOC=$(jq -r '.language // "es"' "$RICE" 2>/dev/null) || LOC=es
fi
case "$LOC" in
	en) ;;
	*) LOC=es ;;
esac

if [ "$LOC" = en ]; then
	N_TERM="Open terminal here";       D_TERM="Opens kitty in this folder"
	N_YAZI="Open in yazi";             D_YAZI="The same place, in the terminal file manager"
	N_CODE="Open in VS Code";          D_CODE="Opens the folder or the file in VS Code"
	N_FONDO="Set as wallpaper";        D_FONDO="Changes the wallpaper and re-themes the whole desktop with this image"
	N_RUTA="Copy path";                D_RUTA="Puts the full path in the clipboard"
else
	N_TERM="Abrir terminal aquí";      D_TERM="Abre kitty en esta carpeta"
	N_YAZI="Abrir en yazi";            D_YAZI="El mismo sitio, en el explorador de terminal"
	N_CODE="Abrir en VS Code";         D_CODE="Abre la carpeta o el fichero en VS Code"
	N_FONDO="Poner de fondo de pantalla"; D_FONDO="Cambia el fondo y re-tematiza el escritorio entero con esta imagen"
	N_RUTA="Copiar la ruta";           D_RUTA="Deja la ruta completa en el portapapeles"
fi

mkdir -p "$(dirname "$DESTINO")"
tmp="$DESTINO.tmp"

# Thunar watches uca.xml and reloads the menu by itself, so there is no need to
# close it. The file is written whole and moved over the old one: if it were
# written in place, an open menu could read it half-written.
cat > "$tmp" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by thunar-language.sh. Do not edit by hand: rewritten when the
     rice language changes. To add an action, edit the script. -->
<actions>
<action>
	<icon>utilities-terminal</icon>
	<name>${N_TERM}</name>
	<submenu></submenu>
	<unique-id>rice-kitty</unique-id>
	<command>kitty --working-directory %f</command>
	<description>${D_TERM}</description>
	<range></range>
	<patterns>*</patterns>
	<startup-notify/>
	<directories/>
</action>
<action>
	<icon>system-file-manager</icon>
	<name>${N_YAZI}</name>
	<submenu></submenu>
	<unique-id>rice-yazi</unique-id>
	<command>kitty --working-directory %f -e yazi</command>
	<description>${D_YAZI}</description>
	<range></range>
	<patterns>*</patterns>
	<startup-notify/>
	<directories/>
</action>
<action>
	<icon>vscode</icon>
	<name>${N_CODE}</name>
	<submenu></submenu>
	<unique-id>rice-vscode</unique-id>
	<command>code %f</command>
	<description>${D_CODE}</description>
	<range></range>
	<patterns>*</patterns>
	<startup-notify/>
	<directories/>
	<text-files/>
	<other-files/>
</action>
<action>
	<icon>preferences-desktop-wallpaper</icon>
	<name>${N_FONDO}</name>
	<submenu></submenu>
	<unique-id>rice-wallpaper</unique-id>
	<command>$HOME/.config/hypr/set-wallpaper.sh %f</command>
	<description>${D_FONDO}</description>
	<range></range>
	<patterns>*</patterns>
	<image-files/>
</action>
<action>
	<icon>edit-copy</icon>
	<name>${N_RUTA}</name>
	<submenu></submenu>
	<unique-id>rice-copiar-ruta</unique-id>
	<command>sh -c 'printf %s "\$0" | wl-copy' %f</command>
	<description>${D_RUTA}</description>
	<range></range>
	<patterns>*</patterns>
	<directories/>
	<audio-files/>
	<image-files/>
	<other-files/>
	<text-files/>
	<video-files/>
</action>
</actions>
EOF

mv -f "$tmp" "$DESTINO"
printf '%s\n' "$LOC"
